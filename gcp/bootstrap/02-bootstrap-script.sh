#!/bin/bash

# Terraform State Bootstrap Script for GCP
# This script creates the necessary GCS bucket and configuration for remote state

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

print_status() { echo -e "${BLUE}[INFO]${NC} $1"; }
print_success() { echo -e "${GREEN}[SUCCESS]${NC} $1"; }
print_warning() { echo -e "${YELLOW}[WARNING]${NC} $1"; }
print_error() { echo -e "${RED}[ERROR]${NC} $1"; }

# Configuration
PROJECT_ID=""
ENVIRONMENT=""
REGION="us-central1"
BUCKET_PREFIX="terraform-state"

# Function to show usage
show_usage() {
    echo "Usage: $0 -p PROJECT_ID -e ENVIRONMENT [-r REGION]"
    echo ""
    echo "Options:"
    echo "  -p PROJECT_ID    GCP Project ID (required)"
    echo "  -e ENVIRONMENT   Environment (dev/stg/prd) (required)"
    echo "  -r REGION        GCP Region (default: us-central1)"
    echo "  -h               Show this help message"
    echo ""
    echo "Example:"
    echo "  $0 -p my-gcp-project -e dev"
    echo "  $0 -p my-gcp-project -e prd -r us-east1"
}

# Parse command line arguments
while getopts "p:e:r:h" opt; do
    case $opt in
        p) PROJECT_ID="$OPTARG" ;;
        e) ENVIRONMENT="$OPTARG" ;;
        r) REGION="$OPTARG" ;;
        h) show_usage; exit 0 ;;
        *) show_usage; exit 1 ;;
    esac
done

# Validate required parameters
if [[ -z "$PROJECT_ID" || -z "$ENVIRONMENT" ]]; then
    print_error "Missing required parameters"
    show_usage
    exit 1
fi

# Validate environment
if [[ ! "$ENVIRONMENT" =~ ^(dev|stg|prd)$ ]]; then
    print_error "Environment must be one of: dev, stg, prd"
    exit 1
fi

# Set bucket name
BUCKET_NAME="${PROJECT_ID}-${BUCKET_PREFIX}-${ENVIRONMENT}"

print_status "Starting Terraform state bootstrap for:"
print_status "  Project: $PROJECT_ID"
print_status "  Environment: $ENVIRONMENT"
print_status "  Region: $REGION"
print_status "  Bucket: $BUCKET_NAME"

# Check if privilege verification script exists and offer to run it
if [[ -f "verify-privileges.sh" ]]; then
    echo
    read -p "Do you want to run privilege verification first? (recommended) (y/n): " -n 1 -r
    echo
    if [[ $REPLY =~ ^[Yy]$ ]]; then
        print_status "Running privilege verification..."
        if ./verify-privileges.sh -p "$PROJECT_ID"; then
            print_success "Privilege verification passed"
        else
            print_error "Privilege verification failed. Please fix issues before continuing."
            exit 1
        fi
        echo
    fi
fi

# Check if gcloud is installed and authenticated
if ! command -v gcloud &> /dev/null; then
    print_error "gcloud CLI is not installed. Please install it first."
    exit 1
fi

# Check if user is authenticated
if ! gcloud auth list --filter=status:ACTIVE --format="value(account)" | grep -q .; then
    print_error "Not authenticated with gcloud. Please run: gcloud auth login"
    exit 1
fi

# Set the project
print_status "Setting GCP project to $PROJECT_ID"
gcloud config set project "$PROJECT_ID"

# Enable required APIs
print_status "Enabling required APIs..."
gcloud services enable storage.googleapis.com
gcloud services enable cloudresourcemanager.googleapis.com

# Check if bucket already exists
if gsutil ls -b gs://"$BUCKET_NAME" &> /dev/null; then
    print_warning "Bucket gs://$BUCKET_NAME already exists"
    read -p "Do you want to continue and update its configuration? (y/n): " -n 1 -r
    echo
    if [[ ! $REPLY =~ ^[Yy]$ ]]; then
        print_status "Aborted by user"
        exit 0
    fi
else
    # Create the bucket
    print_status "Creating GCS bucket: gs://$BUCKET_NAME"
    gsutil mb -p "$PROJECT_ID" -c STANDARD -l "$REGION" gs://"$BUCKET_NAME"
    print_success "Bucket created successfully"
fi

# Enable versioning
print_status "Enabling versioning on bucket"
gsutil versioning set on gs://"$BUCKET_NAME"

# Create and apply lifecycle policy
print_status "Setting up lifecycle policy"
cat > /tmp/lifecycle.json << EOF
{
  "lifecycle": {
    "rule": [
      {
        "action": {"type": "Delete"},
        "condition": {
          "age": 30,
          "isLive": false
        }
      }
    ]
  }
}
EOF

gsutil lifecycle set /tmp/lifecycle.json gs://"$BUCKET_NAME"
rm /tmp/lifecycle.json

# Set bucket permissions (remove public access)
print_status "Securing bucket permissions"
gsutil iam ch -d allUsers:objectViewer gs://"$BUCKET_NAME" 2>/dev/null || true
gsutil iam ch -d allAuthenticatedUsers:objectViewer gs://"$BUCKET_NAME" 2>/dev/null || true

# Create backend configuration file
BACKEND_CONFIG_FILE="backend-${ENVIRONMENT}.hcl"
print_status "Creating backend configuration file: $BACKEND_CONFIG_FILE"

cat > "$BACKEND_CONFIG_FILE" << EOF
# Backend configuration for $ENVIRONMENT environment
# Generated by bootstrap script on $(date)

bucket = "$BUCKET_NAME"
prefix = "terraform/state"
EOF

# Create terraform backend configuration
TERRAFORM_BACKEND_FILE="terraform-backend-${ENVIRONMENT}.tf"
print_status "Creating Terraform backend file: $TERRAFORM_BACKEND_FILE"

cat > "$TERRAFORM_BACKEND_FILE" << EOF
# Terraform backend configuration for $ENVIRONMENT environment
# Generated by bootstrap script on $(date)
# 
# To use this configuration:
# 1. Copy this content to your environment's terraform.tf file
# 2. Run: terraform init
# 3. Terraform will prompt to migrate existing state (if any)

terraform {
  backend "gcs" {
    bucket = "$BUCKET_NAME"
    prefix = "terraform/state"
  }
}
EOF

# Create migration script
MIGRATION_SCRIPT="migrate-to-remote-${ENVIRONMENT}.sh"
print_status "Creating migration script: $MIGRATION_SCRIPT"

cat > "$MIGRATION_SCRIPT" << EOF
#!/bin/bash
# Migration script for $ENVIRONMENT environment
# Generated by bootstrap script on $(date)

set -e

ENVIRONMENT="$ENVIRONMENT"
SCRIPT_DIR="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
ENV_DIR="\$SCRIPT_DIR/../environments/\$ENVIRONMENT"

echo "Migrating \$ENVIRONMENT environment to remote state..."

# Check if environment directory exists
if [ ! -d "\$ENV_DIR" ]; then
    echo "Error: Environment directory not found: \$ENV_DIR"
    exit 1
fi

cd "\$ENV_DIR"

# Backup existing state if it exists
if [ -f "\$ENVIRONMENT.tfstate" ]; then
    echo "Backing up existing state file..."
    cp "\$ENVIRONMENT.tfstate" "\$ENVIRONMENT.tfstate.backup.\$(date +%Y%m%d_%H%M%S)"
fi

# Update terraform.tf with new backend configuration
echo "Updating terraform.tf with remote backend configuration..."

# Create backup of current terraform.tf
cp terraform.tf terraform.tf.backup.\$(date +%Y%m%d_%H%M%S)

# Update the backend configuration
cat > terraform.tf << 'TERRAFORM_EOF'
# $ENVIRONMENT Environment Terraform Configuration
terraform {
  required_version = ">= 1.0"
  
  required_providers {
    google = {
      source  = "hashicorp/google"
      version = "~> 5.0"
    }
    google-beta = {
      source  = "hashicorp/google-beta"
      version = "~> 5.0"
    }
  }

  backend "gcs" {
    bucket = "$BUCKET_NAME"
    prefix = "terraform/state"
  }
}

# Configure the Google Cloud Provider
provider "google" {
  project = var.project_id
  region  = var.region
  zone    = var.zone
}

# Configure the Google Cloud Beta Provider
provider "google-beta" {
  project = var.project_id
  region  = var.region
  zone    = var.zone
}
TERRAFORM_EOF

echo "Initializing Terraform with remote backend..."
terraform init

echo "Migration completed successfully!"
echo "Your state is now stored in: gs://$BUCKET_NAME/terraform/state"
EOF

chmod +x "$MIGRATION_SCRIPT"

# Summary
print_success "Bootstrap completed successfully!"
echo ""
print_status "Created files:"
print_status "  - $BACKEND_CONFIG_FILE (backend configuration)"
print_status "  - $TERRAFORM_BACKEND_FILE (terraform configuration)"
print_status "  - $MIGRATION_SCRIPT (migration script)"
echo ""
print_status "Next steps:"
print_status "  1. Review the generated files"
print_status "  2. Run the migration script: ./$MIGRATION_SCRIPT"
print_status "  3. Or manually update your terraform.tf and run 'terraform init'"
echo ""
print_status "Bucket details:"
print_status "  - Name: gs://$BUCKET_NAME"
print_status "  - Region: $REGION"
print_status "  - Versioning: Enabled"
print_status "  - Lifecycle: Delete old versions after 30 days"
echo ""
print_warning "Important: Keep the generated files secure and version controlled"
print_warning "The bucket contains sensitive state information"